    public async Task<List<DictTable>> GetDataDictionaryAsync()
    {
        using var conn = db.Create();
        var cols = await conn.QueryAsync<DictColumn>(
            @"SELECT c.TABLE_NAME AS TableName, t.TABLE_TYPE AS TableType, c.COLUMN_NAME AS ColumnName, c.ORDINAL_POSITION AS OrdinalPosition,
                     c.DATA_TYPE AS DataType, c.CHARACTER_MAXIMUM_LENGTH AS CharacterMaximumLength, c.NUMERIC_PRECISION AS NumericPrecision,
                     c.NUMERIC_SCALE AS NumericScale, c.IS_NULLABLE AS IsNullable, c.COLUMN_DEFAULT AS ColumnDefault,
                     CAST(ISNULL(COLUMNPROPERTY(OBJECT_ID(QUOTENAME(c.TABLE_SCHEMA) + '.' + QUOTENAME(c.TABLE_NAME)), c.COLUMN_NAME, 'IsIdentity'), 0) AS BIT) AS IsIdentity,
                     CAST(ISNULL(COLUMNPROPERTY(OBJECT_ID(QUOTENAME(c.TABLE_SCHEMA) + '.' + QUOTENAME(c.TABLE_NAME)), c.COLUMN_NAME, 'IsComputed'), 0) AS BIT) AS IsComputed
              FROM INFORMATION_SCHEMA.COLUMNS c
              INNER JOIN INFORMATION_SCHEMA.TABLES t ON t.TABLE_SCHEMA = c.TABLE_SCHEMA AND t.TABLE_NAME = c.TABLE_NAME
              WHERE c.TABLE_SCHEMA = 'dbo' AND c.TABLE_NAME NOT LIKE 'sys%' AND c.TABLE_NAME <> '__RefactorLog'
              ORDER BY t.TABLE_TYPE, c.TABLE_NAME, c.ORDINAL_POSITION");
        var counts = (await conn.QueryAsync<(string Name, long Rows)>(
            @"SELECT t.name AS Name, CAST(SUM(p.rows) AS BIGINT) AS Rows FROM sys.tables t
              INNER JOIN sys.partitions p ON p.object_id = t.object_id AND p.index_id IN (0, 1)
              GROUP BY t.name")).ToDictionary(x => x.Name, x => x.Rows, StringComparer.OrdinalIgnoreCase);

        var order = TableInfo.Keys.Select((k, i) => (k, i)).ToDictionary(x => x.k, x => x.i, StringComparer.OrdinalIgnoreCase);
        return cols.GroupBy(c => c.TableName).Select(g =>
        {
            var info = TableInfo.TryGetValue(g.Key, out var ti) ? ti : (g.First().TableType == "VIEW" ? "Views" : "Other", "");
            return new DictTable
            {
                Name = g.Key,
                Type = g.First().TableType == "VIEW" ? "View" : "Table",
                Module = info.Item1,
                Description = info.Item2,
                RowCount = counts.TryGetValue(g.Key, out var n) ? n : null,
                Columns = g.OrderBy(c => c.OrdinalPosition).ToList()
            };
        })
        .OrderBy(t => t.Type == "View" ? 1 : 0)
        .ThenBy(t => order.TryGetValue(t.Name, out var i) ? i : 999)
        .ThenBy(t => t.Name).ToList();
    }

