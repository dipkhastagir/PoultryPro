    public async Task<ResearchIndexVm> GetIndexAsync()
    {
        using var conn = db.Create();
        var vm = new ResearchIndexVm
        {
            Farms = (await conn.QueryAsync<Farm>("SELECT * FROM Farms WHERE IsActive = 1 ORDER BY Name")).ToList()
        };
        foreach (var d in Defs)
        {
            int rows = d.Key == "batches"
                ? await conn.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM Batches")
                : await conn.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM (" + d.Sql + ") x");
            vm.Datasets.Add(new ResearchDataset
            {
                Key = d.Key, Name = d.Name, Icon = d.Icon, Description = d.Description, Source = d.Source, Unit = d.Unit,
                Rows = rows, FarmFilter = d.FarmCol != null, DateFilter = d.DateCol != null
            });
        }
        var span = await conn.QuerySingleOrDefaultAsync<(DateTime? First, DateTime? Last)>("SELECT MIN(RecordDate), MAX(RecordDate) FROM DailyFarmRecords");
        vm.FirstRecord = span.First; vm.LastRecord = span.Last;
        vm.Batches = await conn.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM Batches");
        vm.FarmCount = vm.Farms.Count;
        return vm;
    }

    public async Task<(IEnumerable<dynamic> Rows, string FileName)?> ExportAsync(string dataset, int? farmId, DateTime? from, DateTime? to)
    {
        var def = Defs.FirstOrDefault(d => d.Key.Equals(dataset ?? "", StringComparison.OrdinalIgnoreCase));
        if (def == null) return null;
        using var conn = db.Create();
        var suffix = (farmId.HasValue ? $"_farm{farmId}" : "") + (from.HasValue ? $"_from{from:yyyyMMdd}" : "") + (to.HasValue ? $"_to{to:yyyyMMdd}" : "");
        var file = $"poultrypro_{def.Key}{suffix}_{DateTime.Today:yyyyMMdd}.csv";

        if (def.Key == "batches")
        {
            var rows = (await conn.QueryAsync("sp_BatchKpiReport", new { FarmId = farmId, ActiveOnly = false }, commandType: CommandType.StoredProcedure)).ToList();
            if (from.HasValue || to.HasValue)
                rows = rows.Where(r =>
                {
                    var d = (IDictionary<string, object>)r;
                    if (!d.TryGetValue("PlacementDate", out var v) || v is not DateTime pd) return true;
                    return (!from.HasValue || pd >= from.Value.Date) && (!to.HasValue || pd <= to.Value.Date);
                }).ToList();
            return (rows, file);
        }

        var sql = def.Sql;
        if (farmId.HasValue && def.FarmCol != null) sql += $" AND {def.FarmCol} = @farmId";
        if (from.HasValue && def.DateCol != null) sql += $" AND {def.DateCol} >= @from";
        if (to.HasValue && def.DateCol != null) sql += $" AND {def.DateCol} < @toExcl";
        sql += " ORDER BY " + def.Order;
        var data = await conn.QueryAsync(sql, new { farmId, from = from?.Date, toExcl = to?.Date.AddDays(1) }, commandTimeout: 120);
        return (data.ToList(), file);
    }

