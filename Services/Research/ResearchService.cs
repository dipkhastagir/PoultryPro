    public async Task<CorrelationVm> GetCorrelationsAsync(string? batchType, int? farmId)
    {
        using var conn = db.Create();
        var vm = new CorrelationVm
        {
            BatchType = string.IsNullOrWhiteSpace(batchType) ? null : batchType,
            FarmId = farmId,
            Farms = (await conn.QueryAsync<Farm>("SELECT * FROM Farms WHERE IsActive = 1 ORDER BY Name")).ToList(),
            Variables = new() { "Age", "Temperature", "Humidity", "THI", "Feed / bird", "Water : feed", "Mortality", "Weight gain" },
            Units = new() { "days", "°C", "% RH", "index", "g/day", "L/kg", "%/day", "g/day" }
        };
        var where = "1 = 1";
        if (vm.BatchType != null) where += " AND b.BatchType = @batchType";
        if (farmId.HasValue) where += " AND d.FarmId = @farmId";
        var rows = await AnalyticsCore.DailyAsync(conn, where, new { batchType = vm.BatchType, farmId });

        var obs = new List<double?[]>();
        foreach (var g in rows.GroupBy(r => r.BatchId))
        {
            var list = g.OrderBy(r => r.RecordDate).ToList();
            for (int i = 0; i < list.Count; i++)
            {
                var r = list[i];
                if (r.StartCount <= 0) continue;
                double? gain = null;
                if (i > 0 && (r.RecordDate - list[i - 1].RecordDate).Days == 1 && r.AverageWeightGm > 0 && list[i - 1].AverageWeightGm > 0)
                    gain = (double)(r.AverageWeightGm!.Value - list[i - 1].AverageWeightGm!.Value);
                obs.Add(new double?[]
                {
                    r.AgeInDays,
                    r.TemperatureC.HasValue ? (double)r.TemperatureC.Value : null,
                    r.HumidityPercent.HasValue ? (double)r.HumidityPercent.Value : null,
                    r.Thi,
                    r.FeedPerBirdGm > 0 ? r.FeedPerBirdGm : null,
                    r.FeedConsumptionKg > 0 && r.WaterConsumptionLtr > 0 ? (double)(r.WaterConsumptionLtr / r.FeedConsumptionKg) : null,
                    r.MortPct,
                    gain
                });
            }
        }
        vm.Observations = obs.Count;
        int k = vm.Variables.Count;
        vm.R = new double?[k, k]; vm.N = new int[k, k]; vm.P = new double[k, k];
        for (int i = 0; i < k; i++)
            for (int j = 0; j < k; j++)
            {
                var pairs = obs.Where(o => o[i].HasValue && o[j].HasValue).ToList();
                vm.N[i, j] = pairs.Count;
                if (i == j) { vm.R[i, j] = pairs.Count > 0 ? 1 : null; vm.P[i, j] = 0; continue; }
                if (pairs.Count < 5) { vm.R[i, j] = null; vm.P[i, j] = 1; continue; }
                var r = PoultryMath.Pearson(pairs.Select(o => o[i]!.Value).ToList(), pairs.Select(o => o[j]!.Value).ToList());
                vm.R[i, j] = Math.Round(r, 3);
                vm.P[i, j] = AnalyticsCore.PearsonP(r, pairs.Count);
            }
        for (int i = 0; i < k; i++)
            for (int j = i + 1; j < k; j++)
                if (vm.R[i, j].HasValue) vm.Strongest.Add((vm.Variables[i], vm.Variables[j], vm.R[i, j]!.Value, vm.N[i, j]));
        vm.Strongest = vm.Strongest.OrderByDescending(x => Math.Abs(x.R)).Take(6).ToList();
        return vm;
    }
